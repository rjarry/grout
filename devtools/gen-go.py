def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "-o",
        "--output-dir",
        required=True,
        help="Directory to write generated Go files into",
    )
    parser.add_argument(
        "-d",
        "--diff-dir",
        help="Compare generated files against this directory and fail if "
        "any differ (for build-time staleness check)",
    )
    parser.add_argument(
        "-s",
        "--stamp",
        help="Touch this file on success (for meson custom_target output)",
    )
    parser.add_argument(
        "--cc",
        required=True,
        help="C compiler command (space-separated, as passed by meson)",
    )
    parser.add_argument(
        "headers",
        nargs="+",
        help="API header files (as passed by meson)",
    )
    args = parser.parse_args()

    gofmt = shutil.which("gofmt")
    if not gofmt:
        print("error: gofmt not found", file=sys.stderr)
        return 1

    build_modules(args.headers)
    ctx = Ctx()

    print("Compiling API headers...", file=sys.stderr)
    obj_path = compile_headers(args.cc, args.headers)
    try:
        print("Extracting DWARF info...", file=sys.stderr)
        extract_all_from_dwarf(ctx, obj_path)
    finally:
        os.unlink(obj_path)

    if "cpu_set_t" in ctx.type_sizes:
        entry = SPECIAL_TYPE_MAP["cpu_set_t"]
        SPECIAL_TYPE_MAP["cpu_set_t"] = (
            entry[0], ctx.type_sizes["cpu_set_t"], entry[2], entry[3],
        )

    all_enums = build_enum_infos(ctx)
    all_structs = build_struct_infos(ctx)
    all_reqs = build_request_infos(ctx)
    all_events = build_event_infos(ctx)
    all_defines = build_defines(ctx, args.headers)

    for ei in all_enums:
        ctx.enums_by_mod.setdefault(
            struct_source_module(ei.c_name) or "types", []
        ).append(ei)
    for si in all_structs:
        ctx.structs_by_mod.setdefault(
            struct_source_module(si.c_name) or "types", []
        ).append(si)
    for ri in all_reqs:
        ctx.reqs_by_mod.setdefault(
            struct_source_module(ri.name) or "api", []
        ).append(ri)
    for ei in all_events:
        ctx.events_by_mod.setdefault(
            struct_source_module(ei.name) or "api", []
        ).append(ei)
    for name, val, go_type in all_defines:
        ctx.defines_by_mod.setdefault(
            struct_source_module(name) or "api", []
        ).append((name, val, go_type))

    output_dir = args.output_dir
    os.makedirs(output_dir, exist_ok=True)

    for module_name in MODULES:
        filename = f"gen_{module_name}.go"
        filepath = os.path.join(output_dir, filename)
        content = generate_module(ctx, module_name)
        result = subprocess.run(
            [gofmt],
            input=content,
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            print(
                f"error: gofmt failed on {filename}:\n{result.stderr}", file=sys.stderr
            )
            return 1
        with open(filepath, "w") as f:
            f.write(result.stdout)
        print(f"  wrote {filepath}", file=sys.stderr)

    if args.diff_dir:
        stale = []
        for module_name in MODULES:
            filename = f"gen_{module_name}.go"
            gen_path = os.path.join(output_dir, filename)
            src_path = os.path.join(args.diff_dir, filename)

            with open(gen_path) as f:
                generated = f.read()

            if os.path.exists(src_path):
                with open(src_path) as f:
                    existing = f.read()
                if existing != generated:
                    stale.append(filename)
                    diff = difflib.unified_diff(
                        existing.splitlines(keepends=True),
                        generated.splitlines(keepends=True),
                        fromfile=f"a/go/{filename}",
                        tofile=f"b/go/{filename}",
                    )
                    sys.stderr.writelines(diff)
            else:
                stale.append(filename)
                print(f"  {src_path}: missing", file=sys.stderr)

        if stale:
            print(
                f"\nStale generated files: {', '.join(stale)}",
                file=sys.stderr,
            )
            print("Run 'ninja update-go' to regenerate.", file=sys.stderr)
            return 1
        print("Generated files are up to date.", file=sys.stderr)

    if args.stamp:
        with open(args.stamp, "w") as f:
            f.write("")

    return 0


if __name__ == "__main__":
    sys.exit(main())
