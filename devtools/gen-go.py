def dwarf_resolve_type(die):
    if "DW_AT_type" not in die.attributes:
        return None
    ref = die.attributes["DW_AT_type"].value
    return die.cu.get_DIE_from_refaddr(ref + die.cu.cu_offset)


def dwarf_name(die):
    n = die.attributes.get("DW_AT_name")
    return n.value.decode() if n else None


def dwarf_unwrap_typedef(die):
    while die and die.tag == "DW_TAG_typedef":
        die = dwarf_resolve_type(die)
    return die


def dwarf_type_name(die):
    """Get the C type name, following typedefs."""
    if die is None:
        return "void"
    name = dwarf_name(die)
    if name:
        return name
    if die.tag == "DW_TAG_pointer_type":
        return dwarf_type_name(dwarf_resolve_type(die))
    if die.tag == "DW_TAG_typedef":
        return dwarf_name(die) or dwarf_type_name(dwarf_resolve_type(die))
    if die.tag == "DW_TAG_const_type":
        return dwarf_type_name(dwarf_resolve_type(die))
    return None


def dwarf_byte_size(die):
    """Get DW_AT_byte_size, following type references if needed."""
    if die is None:
        return 0
    sz = die.attributes.get("DW_AT_byte_size")
    if sz:
        return sz.value
    if die.tag == "DW_TAG_typedef":
        return dwarf_byte_size(dwarf_resolve_type(die))
    return 0


def dwarf_go_int_type(size_bytes):
    return {1: "uint8", 2: "uint16", 4: "uint32", 8: "uint64"}.get(
        size_bytes, f"[{size_bytes}]byte"
    )


