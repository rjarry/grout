def generate_module(ctx, module_name):
    enums = ctx.enums_by_mod.get(module_name, [])
    structs = ctx.structs_by_mod.get(module_name, [])
    req_infos = ctx.reqs_by_mod.get(module_name, [])
    event_infos = ctx.events_by_mod.get(module_name, [])
    defines = ctx.defines_by_mod.get(module_name, [])

    assign_go_types(structs, enums)
    for si in structs:
        si.update_flex()

    body = io.StringIO()

    for ei in enums:
        generate_enum(body, ei)

    generate_defines(body, defines)

    if module_name == "api":
        ev_sz = ctx.type_sizes.get("gr_api_event", 16)
        req_sz = ctx.type_sizes.get("gr_api_request", 12)
        resp_sz = ctx.type_sizes.get("gr_api_response", 12)
        body.write("const (\n")
        body.write(f"\teventHeaderSize = {ev_sz}\n")
        body.write(f"\treqHeaderSize = {req_sz}\n")
        body.write(f"\trespHeaderSize = {resp_sz}\n\n")
        body.write(")\n\n")

    for si in structs:
        generate_struct(body, si)
        generate_unmarshal(body, si)
        generate_marshal(body, si)

    generate_request_const(body, req_infos, event_infos)
    generate_api_methods(body, req_infos)

    if event_infos:
        generate_event_decoders(body, event_infos)

    body_str = body.getvalue()

    buf = io.StringIO()
    buf.write(HEADER)
    buf.write("package grout\n\n")

    imports = []
    if needs_import(body_str, "fmt"):
        imports.append('"fmt"')
    if needs_import(body_str, "iter"):
        imports.append('"iter"')
    if needs_import(body_str, "net/netip"):
        imports.append('"net/netip"')

    if imports:
        if len(imports) == 1:
            buf.write(f"import {imports[0]}\n\n")
        else:
            buf.write("import (\n")
            for imp in imports:
                buf.write(f"\t{imp}\n")
            buf.write(")\n\n")

    buf.write(body_str)
    return buf.getvalue()


