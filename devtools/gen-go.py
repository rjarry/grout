def build_enum_infos(ctx):
    enums = []
    seen = set()

    for name, (size, constants) in ctx.raw_enums.items():
        if name in seen:
            continue
        # Skip request/event enum types — their constants are emitted
        # separately by generate_request_const.
        if name.endswith("_requests") or name.endswith("_events"):
            continue
        if name == "__gen_defines":
            continue
        # Skip system enums (e.g. __socket_type from sys/socket.h)
        if not (name.startswith("gr_") or name.startswith("dhcp_")
                or name.startswith("addr_") or name.startswith("conn_")):
            continue
        seen.add(name)

        go_name = c_to_go_name(name)
        go_underlying = dwarf_go_int_type(size)
        go_constants = []
        for cname, cval in constants:
            go_cname = c_enum_const_to_go(name, cname)
            go_constants.append((go_cname, cval))

        ei = EnumInfo(name, go_name, go_underlying, go_constants)
        enums.append(ei)
        KNOWN_ENUMS[name] = go_name

    return enums


def build_struct_infos(ctx):
    structs = []
    seen = set()

    for name, (die, size) in ctx.raw_structs.items():
        if name in seen:
            continue

        # Skip types handled by hand-written Go code
        if name in SPECIAL_TYPE_MAP or name in STRUCT_TYPE_MAP:
            continue
        if name in ("rte_ipv6_addr", "rte_ether_addr", "ip4_net", "ip6_net", "l3_addr"):
            continue
        # Skip *_base structs (flattened via BASE())
        if name.endswith("_base"):
            continue
        # Skip internal/system structs
        if not name.startswith("gr_") and name not in (
            "rte_ether_addr",
            "ip4_net",
            "ip6_net",
        ):
            continue

        seen.add(name)
        fields = extract_struct_fields_dwarf(die)
        si = StructInfo(name, size, fields)
        structs.append(si)
        KNOWN_STRUCTS[name] = si.go_name
        if si.has_flexible_array:
            FLEXIBLE_STRUCTS.add(name)

    return structs


def build_request_infos(ctx):
    infos = []
    for req_name, req_struct, resp_struct, is_stream in ctx.raw_requests:
        type_val = ctx.enum_values.get(req_name, 0)
        if type_val == 0:
            continue
        infos.append(
            RequestInfo(req_name, type_val, req_struct, resp_struct, is_stream)
        )
    return infos


def build_event_infos(ctx):
    infos = []
    for ev_name, payload_struct in ctx.raw_events:
        type_val = ctx.enum_values.get(ev_name, 0)
        if type_val == 0:
            continue
        infos.append(EventInfo(ev_name, type_val, payload_struct))
    return infos


def build_defines(ctx, header_paths):
    """Build define list. Integer values come from DWARF, string values
    from regex (DWARF can't store string initializer values)."""
    result = []

    for name, val in sorted(ctx.defines_int.items()):
        if val > (1 << 32):
            result.append((name, val, "uint64"))
        else:
            result.append((name, val, ""))

    # String defines: read values from source
    for path in header_paths:
        if not os.path.exists(path):
            continue
        with open(path) as f:
            content = f.read()
        for m in STR_DEFINE_RE.finditer(content):
            dname, dval = m.groups()
            result.append((dname, dval, "string"))

    return result


