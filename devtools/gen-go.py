# GR_BIT64(n), plain integers, hex, parenthesized expressions
INT_DEFINE_RE = re.compile(
    r"""
    #define\s+
    (GR_\w+)\s+
    (?:
        GR_BIT\d+\(\d+\)|
        \(?\d[\d\s*]*\)?|
        (?:UINT\d+_C\()?0x[0-9a-fA-F]+\)?
    )\s*$
    """,
    re.MULTILINE | re.VERBOSE,
)
STR_DEFINE_RE = re.compile(r'#define\s+(GR_\w+)\s+"([^"]+)"')


def scan_define_names(header_paths):
    """Scan headers for #define GR_* names to expose via const variables."""
    int_defines = []
    str_defines = []

    for path in header_paths:
        if not os.path.exists(path):
            continue
        with open(path) as f:
            content = f.read()

        for m in INT_DEFINE_RE.finditer(content):
            name = m.group(1)
            if "_MODULE" in name or "_RE" in name:
                continue
            int_defines.append(name)

        for m in STR_DEFINE_RE.finditer(content):
            str_defines.append(m.group(1))

    return int_defines, str_defines


def compile_headers(cc_cmd, header_paths):
    """Generate a C file, compile it with debug info, return path to .o."""
    int_defs, str_defs = scan_define_names(header_paths)

    c_src = []
    # Override macros before including headers
    c_src.append(
        """\
#define GR_REQ(r, req, resp) \\
    resp *r##_(req *a) { return (void *)0; }
#define GR_REQ_STREAM(r, req, resp) \\
    resp *r##_stream_(req *a) { return (void *)0; }
#define GR_EVENT(e, obj) \\
    obj *e##_event_(void) { return (void *)0; }
#define GR_API_INLINE static __attribute__((unused))
"""
    )

    # Include all headers
    for path in header_paths:
        basename = os.path.basename(path)
        if basename in SKIP_HEADERS:
            continue
        c_src.append(f"#include <{basename}>")

    c_src.append("")

    # Emit #define values as enum constants so DWARF stores the values.
    # (static const variables don't get DW_AT_const_value with -O0.)
    if int_defs:
        c_src.append("enum __gen_defines {")
        for name in int_defs:
            c_src.append(f"\t__DEF_{name} = {name},")
        c_src.append("};")

    # String defines are extracted directly from source via regex
    # since they can't be represented as enum values in C.

    c_src.append("")

    src_text = "\n".join(c_src)

    obj_fd, obj_path = tempfile.mkstemp(suffix=".o")
    os.close(obj_fd)

    # Build include path args
    inc_args = []
    for d in API_DIRS:
        inc_args.extend(["-I", d])

    cmd = shlex.split(cc_cmd)
    cmd += [
        "-c",
        "-g",
        "-fno-eliminate-unused-debug-types",
        "-O0",
        "-Wno-missing-declarations",
        "-Wno-missing-prototypes",
    ]
    cmd += inc_args
    cmd += ["-x", "c", "-o", obj_path, "-"]

    result = subprocess.run(
        cmd,
        input=src_text,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        print(f"error: compilation failed:\n{result.stderr}", file=sys.stderr)
        os.unlink(obj_path)
        sys.exit(1)

    return obj_path


