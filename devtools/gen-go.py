def build_modules(header_paths):
    MODULES.clear()
    API_DIRS.clear()

    seen_dirs = set()
    for path in header_paths:
        basename = os.path.basename(path)
        if basename in SKIP_HEADERS:
            continue
        d = os.path.dirname(os.path.abspath(path))
        if d not in seen_dirs:
            seen_dirs.add(d)
            API_DIRS.append(d)
        if basename in CORE_HEADERS:
            mod = CORE_HEADERS[basename]
        else:
            mod = re.sub(r"^gr_", "", basename)
            mod = re.sub(r"\.h$", "", mod)
        if mod not in MODULES:
            MODULES[mod] = {"headers": [], "source_files": set()}
        MODULES[mod]["headers"].append(basename)
        MODULES[mod]["source_files"].add(basename)


def find_header(basename):
    for d in API_DIRS:
        candidate = os.path.join(d, basename)
        if os.path.exists(candidate):
            return candidate
    return None


