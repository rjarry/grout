_source_module_cache = {}


def struct_source_module(name):
    """Map a C name to its module by searching header files."""
    if name in _source_module_cache:
        return _source_module_cache[name]

    # Try naming convention first
    for mod_name, mod in MODULES.items():
        for hdr in mod["headers"]:
            prefix = re.sub(r"\.h$", "", hdr).replace("gr_", "")
            if name.startswith(f"gr_{prefix}"):
                _source_module_cache[name] = mod_name
                return mod_name

    # Search for definition (not just usage) in header content
    for mod_name, mod in MODULES.items():
        for hdr in mod["source_files"]:
            path = find_header(hdr)
            if not path:
                continue
            with open(path) as f:
                content = f.read()
            if f"struct {name} {{" in content or f"#define {name} " in content \
                    or f"\t{name} " in content or f"\t{name}," in content:
                _source_module_cache[name] = mod_name
                return mod_name

    _source_module_cache[name] = None
    return None


def assign_go_types(structs, enums):
    for si in structs:
        for f in si.fields:
            if f.is_flexible_array:
                f.go_name = c_to_go_name(f.name)
                elem = f.element_type_name
                if elem == "char":
                    f.go_type = "string"
                    f.go_elem_type = "string"
                elif elem in ("uint8_t", "unsigned char"):
                    f.go_type = "[]byte"
                    f.go_elem_type = ""
                else:
                    elem_go = go_type_for_c_type(None, elem)
                    if elem_go:
                        f.go_type = f"[]{elem_go}"
                        f.go_elem_type = elem_go
                    else:
                        f.go_type = "[]byte"
                        f.go_elem_type = ""
                continue

            if f.is_array:
                f.go_name = c_to_go_name(f.name)
                elem_go = go_type_for_c_type(None, f.element_type_name)
                if elem_go:
                    f.go_type = f"[{f.array_size}]{elem_go}"
                else:
                    f.go_type = f"[{f.array_size}]byte"
                continue

            f.go_name = c_to_go_name(f.name)

            m = re.match(r"char\[(\d+)\]", f.c_type_name)
            if m:
                f.go_type = "string"
                f.size = int(m.group(1))
                continue

            gt = go_type_for_c_type(None, f.c_type_name)
            if gt:
                f.go_type = gt
            else:
                f.go_type = f"/* TODO: {f.c_type_name} */ [0]byte"

            if f.c_type_name in FLEXIBLE_STRUCTS:
                f.contains_flex = True


def emit(out, template, **kwargs):
    """Write a template string with {key} substitution to out."""
    out.write(template.format(**kwargs))


def field_getter(f):
    """Return the Go expression to read a field from byte slice b."""
    off = f.offset
    if f.is_bitfield:
        mask = (1 << f.bitfield_width) - 1
        return f"{f.go_type}((b[{off}] >> {f.bit_offset}) & {mask})"
    if re.match(r"char\[(\d+)\]", f.c_type_name):
        return f"getString(b, {off}, {f.size})"
    if f.c_type_name in SPECIAL_TYPE_MAP:
        return f"{SPECIAL_TYPE_MAP[f.c_type_name][2]}(b, {off})"
    if f.c_type_name in KNOWN_ENUMS:
        return f"{KNOWN_ENUMS[f.c_type_name]}(getU8(b, {off}))"
    if f.go_type == "bool":
        return f"getBool(b, {off})"
    getter = {1: "getU8", 2: "getU16", 4: "getU32", 8: "getU64"}.get(f.size)
    if getter:
        return f"{f.go_type}({getter}(b, {off}))"
    return None


def field_putter(f):
    """Return the Go statement to write a field into byte slice b."""
    off = f.offset
    if f.is_bitfield:
        mask = (1 << f.bitfield_width) - 1
        return f"b[{off}] |= byte((uint8(s.{f.go_name}) & {mask}) << {f.bit_offset})"
    if re.match(r"char\[(\d+)\]", f.c_type_name):
        return f"putString(b, {off}, {f.size}, s.{f.go_name})"
    if f.c_type_name in SPECIAL_TYPE_MAP:
        return f"{SPECIAL_TYPE_MAP[f.c_type_name][3]}(b, {off}, s.{f.go_name})"
    if f.go_type == "bool":
        return f"putBool(b, {off}, s.{f.go_name})"
    putter = {1: "putU8", 2: "putU16", 4: "putU32", 8: "putU64"}.get(f.size)
    if putter:
        cast = {1: "uint8", 2: "uint16", 4: "uint32", 8: "uint64"}[f.size]
        return f"{putter}(b, {off}, {cast}(s.{f.go_name}))"
    return None


def generate_enum(out, ei):
    emit(out, "type {name} {underlying}\n\n", name=ei.go_name, underlying=ei.underlying)
    out.write("const (\n")
    for go_name, val in ei.constants:
        emit(out, "\t{name} {typ} = {val}\n", name=go_name, typ=ei.go_name, val=val)
    out.write(")\n\n")


def generate_struct(out, si):
    disc = DISCRIMINATED_INFO.get(si.c_name)
    emit(out, "type {name} struct {{", name=si.go_name)
    if si.fields:
        out.write("\n")
        for f in si.fields:
            if f.go_type.startswith("/* TODO"):
                emit(out, "\t// {name} {typ}\n", name=f.go_name, typ=f.go_type)
            elif f.is_flexible_array and disc and f.go_name == disc["go_field"]:
                emit(out, "\t{name} any\n", name=f.go_name)
            else:
                emit(out, "\t{name} {typ}\n", name=f.go_name, typ=f.go_type)
    out.write("}\n\n")


def generate_unmarshal(out, si):
    emit(
        out,
        """\
func (s *{name}) unmarshal(b []byte) error {{
\tif len(b) < {size} {{
\t\treturn fmt.Errorf("{name}: buffer too short: %d < {size}", len(b))
\t}}
""",
        name=si.go_name,
        size=si.size,
    )

    for f in si.fields:
        if f.go_type.startswith("/* TODO"):
            continue
        if f.is_flexible_array:
            _emit_flex_unmarshal(out, si, f)
            continue

        # Struct types with their own unmarshal
        if f.c_type_name in STRUCT_TYPE_MAP:
            go_t = STRUCT_TYPE_MAP[f.c_type_name]
            if go_t == "IPv4Net":
                emit(
                    out,
                    "\ts.{n} = getIPv4Net(b, {o}, {o4})\n",
                    n=f.go_name,
                    o=f.offset,
                    o4=f.offset + 4,
                )
            elif go_t == "IPv6Net":
                emit(
                    out,
                    "\ts.{n} = getIPv6Net(b, {o}, {o16})\n",
                    n=f.go_name,
                    o=f.offset,
                    o16=f.offset + 16,
                )
            continue
        if f.c_type_name in KNOWN_STRUCTS:
            sl = (
                f"b[{f.offset}:]"
                if f.contains_flex
                else f"b[{f.offset}:{f.offset + f.size}]"
            )
            emit(
                out,
                """\
\tif err := s.{n}.unmarshal({sl}); err != nil {{
\t\treturn err
\t}}
""",
                n=f.go_name,
                sl=sl,
            )
            continue
        if f.is_array:
            elem_go = KNOWN_STRUCTS.get(f.element_type_name, "")
            elem_size = f.size // f.array_size if f.array_size > 0 else 0
            if elem_go and elem_size > 0:
                emit(
                    out,
                    """\
\tfor i := range s.{n} {{
\t\toff := {o} + i*{esz}
\t\tif err := s.{n}[i].unmarshal(b[off:off+{esz}]); err != nil {{
\t\t\treturn err
\t\t}}
\t}}
""",
                    n=f.go_name,
                    o=f.offset,
                    esz=elem_size,
                )
            continue

        # Scalar fields
        expr = field_getter(f)
        if expr:
            emit(out, "\ts.{n} = {expr}\n", n=f.go_name, expr=expr)

    out.write("\treturn nil\n}\n\n")


def _emit_flex_unmarshal(out, si, f):
    disc = DISCRIMINATED_INFO.get(si.c_name)
    if disc and f.go_name == disc["go_field"]:
        emit(
            out,
            "\tif len(b) > {sz} {{\n\t\tinfo := b[{sz}:]\n\t\tswitch s.{d} {{\n",
            sz=si.size,
            d=disc["discriminator"],
        )
        for const_name, info_type in disc["mapping"].items():
            emit(
                out,
                """\
\t\tcase {c}:
\t\t\tvar v {t}
\t\t\tif err := v.unmarshal(info); err != nil {{
\t\t\t\treturn err
\t\t\t}}
\t\t\ts.{n} = &v
""",
                c=const_name,
                t=info_type,
                n=f.go_name,
            )
        out.write("\t\t}\n\t}\n")
    elif f.go_elem_type == "string":
        emit(
            out,
            """\
\tif len(b) > {sz} {{
\t\ts.{n} = getString(b, {sz}, len(b)-{sz})
\t}}
""",
            sz=si.size,
            n=f.go_name,
        )
    elif f.go_elem_type == "netip.Addr" and f.element_type_name == "rte_ipv6_addr":
        emit(
            out,
            """\
\tfor off := {sz}; off+16 <= len(b); off += 16 {{
\t\ts.{n} = append(s.{n}, getIPv6(b, off))
\t}}
""",
            sz=si.size,
            n=f.go_name,
        )
    elif f.element_size > 0 and f.go_elem_type in KNOWN_STRUCTS.values():
        emit(
            out,
            """\
\tfor off := {sz}; off+{esz} <= len(b); off += {esz} {{
\t\tvar elem {t}
\t\tif err := elem.unmarshal(b[off:off+{esz}]); err != nil {{
\t\t\treturn err
\t\t}}
\t\ts.{n} = append(s.{n}, elem)
\t}}
""",
            sz=si.size,
            esz=f.element_size,
            t=f.go_elem_type,
            n=f.go_name,
        )
    elif not f.go_elem_type:
        emit(
            out,
            """\
\tif len(b) > {sz} {{
\t\ts.{n} = make([]byte, len(b)-{sz})
\t\tcopy(s.{n}, b[{sz}:])
\t}}
""",
            sz=si.size,
            n=f.go_name,
        )


def generate_marshal(out, si):
    emit(
        out,
        """\
func (s *{name}) marshal() []byte {{
\tb := make([]byte, {size})
""",
        name=si.go_name,
        size=si.size,
    )

    for f in si.fields:
        if f.go_type.startswith("/* TODO") or f.is_flexible_array:
            continue

        if f.c_type_name in STRUCT_TYPE_MAP:
            go_t = STRUCT_TYPE_MAP[f.c_type_name]
            if go_t == "IPv4Net":
                emit(
                    out,
                    "\tputIPv4Net(b, {o}, {o4}, s.{n})\n",
                    o=f.offset,
                    o4=f.offset + 4,
                    n=f.go_name,
                )
            elif go_t == "IPv6Net":
                emit(
                    out,
                    "\tputIPv6Net(b, {o}, {o16}, s.{n})\n",
                    o=f.offset,
                    o16=f.offset + 16,
                    n=f.go_name,
                )
            continue
        if f.c_type_name in KNOWN_STRUCTS:
            if f.contains_flex:
                emit(
                    out,
                    """\
\t{{
\t\td := s.{n}.marshal()
\t\tcopy(b[{o}:], d[:min(len(d), len(b)-{o})])
\t\tif len(d) > {sz} {{
\t\t\tb = append(b, d[{sz}:]...)
\t\t}}
\t}}
""",
                    n=f.go_name,
                    o=f.offset,
                    sz=f.size,
                )
            else:
                emit(out, "\tcopy(b[{o}:], s.{n}.marshal())\n", o=f.offset, n=f.go_name)
            continue
        if f.is_array:
            continue

        stmt = field_putter(f)
        if stmt:
            emit(out, "\t{stmt}\n", stmt=stmt)

    if si.has_flexible_array:
        for f in si.fields:
            if f.is_flexible_array:
                _emit_flex_marshal(out, si, f)

    out.write("\treturn b\n}\n\n")


def _emit_flex_marshal(out, si, f):
    disc = DISCRIMINATED_INFO.get(si.c_name)
    if disc and f.go_name == disc["go_field"]:
        emit(
            out,
            """\
\tif s.{n} != nil {{
\t\tif m, ok := s.{n}.(marshaler); ok {{
\t\t\tb = append(b, m.marshal()...)
\t\t}}
\t}}
""",
            n=f.go_name,
        )
    elif f.go_elem_type == "string":
        emit(
            out, "\tb = append(b, []byte(s.{n})...)\n\tb = append(b, 0)\n", n=f.go_name
        )
    elif f.go_elem_type == "netip.Addr" and f.element_type_name == "rte_ipv6_addr":
        emit(
            out,
            """\
\tfor _, addr := range s.{n} {{
\t\ta16 := addr.As16()
\t\tb = append(b, a16[:]...)
\t}}
""",
            n=f.go_name,
        )
    elif f.element_size > 0 and f.go_elem_type in KNOWN_STRUCTS.values():
        emit(
            out,
            """\
\tfor i := range s.{n} {{
\t\tb = append(b, s.{n}[i].marshal()...)
\t}}
""",
            n=f.go_name,
        )
    elif not f.go_elem_type:
        emit(out, "\tb = append(b, s.{n}...)\n", n=f.go_name)


def generate_defines(out, defines):
    if not defines:
        return
    out.write("// Constants from #define macros.\nconst (\n")
    for name, val, go_type in defines:
        go_name = c_to_go_name(name)
        if go_type == "string":
            emit(out, '\t{n} = "{v}"\n', n=go_name, v=val)
        elif go_type == "uint64":
            emit(out, "\t{n} uint64 = 0x{v:x}\n", n=go_name, v=val)
        elif isinstance(val, int) and val > 0xFFFF:
            emit(out, "\t{n} = 0x{v:x}\n", n=go_name, v=val)
        else:
            emit(out, "\t{n} = {v}\n", n=go_name, v=val)
    out.write(")\n\n")


def generate_request_const(out, req_infos, event_infos):
    if req_infos:
        out.write("// Request type constants.\nconst (\n")
        for ri in req_infos:
            go_name = "gr" + c_to_go_name(ri.name)
            ri.go_const = go_name[0].lower() + go_name[1:]
            emit(out, "\t{n} uint32 = 0x{v:08x}\n", n=ri.go_const, v=ri.type_val)
        out.write(")\n\n")
    if event_infos:
        out.write("// Event type constants.\nconst (\n")
        for ei in event_infos:
            ei.go_const = c_to_go_name(ei.name)
            emit(out, "\t{n} uint32 = 0x{v:08x}\n", n=ei.go_const, v=ei.type_val)
        out.write(")\n\n")


def generate_api_methods(out, req_infos):
    for ri in req_infos:
        req_go = KNOWN_STRUCTS.get(ri.req_struct)
        resp_go = KNOWN_STRUCTS.get(ri.resp_struct)
        if not req_go and ri.req_struct != "gr_empty":
            continue
        if not resp_go and ri.resp_struct != "gr_empty":
            continue

        method = c_to_go_name(ri.name)
        has_req = ri.req_struct != "gr_empty"
        has_resp = ri.resp_struct != "gr_empty"

        if ri.is_stream:
            if has_req:
                emit(
                    out,
                    """\
func (c *Client) {m}(req *{rq}) iter.Seq2[*{rp}, error] {{
\treturn streamIter[{rp}](c, {k}, req.marshal())
}}

""",
                    m=method,
                    rq=req_go,
                    rp=resp_go,
                    k=ri.go_const,
                )
            else:
                emit(
                    out,
                    """\
func (c *Client) {m}() iter.Seq2[*{rp}, error] {{
\treturn streamIter[{rp}](c, {k}, nil)
}}

""",
                    m=method,
                    rp=resp_go,
                    k=ri.go_const,
                )
        elif not has_resp:
            if has_req:
                emit(
                    out,
                    """\
func (c *Client) {m}(req *{rq}) error {{
\treturn c.sendOnly({k}, req.marshal())
}}

""",
                    m=method,
                    rq=req_go,
                    k=ri.go_const,
                )
            else:
                emit(
                    out,
                    """\
func (c *Client) {m}() error {{
\treturn c.sendOnly({k}, nil)
}}

""",
                    m=method,
                    k=ri.go_const,
                )
        else:
            payload = "req.marshal()" if has_req else "nil"
            sig = f"(req *{req_go})" if has_req else "()"
            emit(
                out,
                """\
func (c *Client) {m}{sig} (*{rp}, error) {{
\tdata, err := c.sendRecv({k}, {p})
\tif err != nil {{
\t\treturn nil, err
\t}}
\tresp := new({rp})
\tif data != nil {{
\t\tif err := resp.unmarshal(data); err != nil {{
\t\t\treturn nil, err
\t\t}}
\t}}
\treturn resp, nil
}}

""",
                m=method,
                sig=sig,
                rp=resp_go,
                k=ri.go_const,
                p=payload,
            )


def generate_event_decoders(out, event_infos):
    out.write("func init() {\n")
    for ei in event_infos:
        payload_go = KNOWN_STRUCTS.get(ei.payload_struct)
        if not payload_go:
            continue
        emit(
            out,
            """\
\tregisterEventDecoder({k}, func(b []byte) (any, error) {{
\t\tv := new({t})
\t\tif err := v.unmarshal(b); err != nil {{
\t\t\treturn nil, err
\t\t}}
\t\treturn v, nil
\t}})
""",
            k=ei.go_const,
            t=payload_go,
        )
    out.write("}\n\n")


def needs_import(content, pkg):
    if pkg == "fmt":
        return "fmt." in content
    if pkg == "iter":
        return "iter.Seq2" in content
    if pkg == "net/netip":
        return "netip." in content
    return False


