def extract_all_from_dwarf(ctx, obj_path):
    """Parse DWARF info, populating ctx with results."""
    with open(obj_path, "rb") as f:
        elf = ELFFile(f)
        dwarf = elf.get_dwarf_info()
        for cu in dwarf.iter_CUs():
            for die in cu.iter_DIEs():
                _process_die(ctx, die)


def _process_die(ctx, die):
    if die.tag == "DW_TAG_typedef":
        name = dwarf_name(die)
        if not name:
            return
        target = dwarf_resolve_type(die)
        if target and target.tag == "DW_TAG_enumeration_type":
            _extract_enum(ctx, name, target)

    elif die.tag == "DW_TAG_enumeration_type":
        name = dwarf_name(die)
        if name == "__gen_defines":
            for child in die.iter_children():
                if child.tag != "DW_TAG_enumerator":
                    continue
                cname = dwarf_name(child)
                if cname and cname.startswith("__DEF_"):
                    cval = child.attributes.get("DW_AT_const_value")
                    if cval is not None:
                        ctx.defines_int[cname[len("__DEF_") :]] = cval.value
        elif name:
            _extract_enum(ctx, name, die)

    elif die.tag == "DW_TAG_structure_type":
        name = dwarf_name(die)
        if not name:
            return
        sz = die.attributes.get("DW_AT_byte_size")
        if not sz:
            return
        if name in ("gr_api_event", "gr_api_request", "gr_api_response", "cpu_set_t"):
            ctx.type_sizes[name] = sz.value
        if name not in ctx.raw_structs:
            ctx.raw_structs[name] = (die, sz.value)

    elif die.tag == "DW_TAG_subprogram":
        name = dwarf_name(die)
        if not name:
            return
        _extract_function(ctx, name, die)


def _extract_enum(ctx, name, die):
    if name in ctx.raw_enums:
        return
    sz = die.attributes.get("DW_AT_byte_size")
    if not sz:
        return
    constants = []
    for child in die.iter_children():
        if child.tag != "DW_TAG_enumerator":
            continue
        cname = dwarf_name(child)
        cval = child.attributes.get("DW_AT_const_value")
        if cname and cval is not None:
            constants.append((cname, cval.value))
            ctx.enum_values[cname] = cval.value
    if constants:
        ctx.raw_enums[name] = (sz.value, constants)


def _extract_function(ctx, name, die):
    if name.endswith("_event_"):
        req_name = name[: -len("_event_")]
        ret_die = dwarf_resolve_type(die)
        if ret_die and ret_die.tag == "DW_TAG_pointer_type":
            payload = dwarf_type_name(dwarf_resolve_type(ret_die))
            if payload:
                ctx.raw_events.append((req_name, payload))
    elif name.endswith("_stream_"):
        _extract_req_resp(ctx, name[: -len("_stream_")], die, is_stream=True)
    elif name.endswith("_"):
        _extract_req_resp(ctx, name[:-1], die, is_stream=False)


def _extract_req_resp(ctx, req_name, die, is_stream):
    ret_die = dwarf_resolve_type(die)
    resp_name = "gr_empty"
    if ret_die and ret_die.tag == "DW_TAG_pointer_type":
        inner = dwarf_type_name(dwarf_resolve_type(ret_die))
        if inner:
            resp_name = inner

    req_sname = "gr_empty"
    for child in die.iter_children():
        if child.tag == "DW_TAG_formal_parameter":
            ptype = dwarf_resolve_type(child)
            if ptype and ptype.tag == "DW_TAG_pointer_type":
                inner = dwarf_type_name(dwarf_resolve_type(ptype))
                if inner:
                    req_sname = inner
            break

    ctx.raw_requests.append((req_name, req_sname, resp_name, is_stream))


def extract_struct_fields_dwarf(die):
    """Extract fields from a DWARF struct DIE, flattening anonymous members."""
    fields = []
    _walk_members(die, die, fields)
    return fields


def _walk_members(struct_die, top_die, fields):
    for child in struct_die.iter_children():
        if child.tag != "DW_TAG_member":
            continue

        name = dwarf_name(child)
        loc = child.attributes.get("DW_AT_data_member_location")
        offset = loc.value if loc else 0

        mtype = dwarf_resolve_type(child)
        if mtype is None:
            continue

        # Anonymous struct/union from BASE() — flatten
        if name is None:
            real_type = dwarf_unwrap_typedef(mtype)
            if real_type and real_type.tag in (
                "DW_TAG_structure_type",
                "DW_TAG_union_type",
            ):
                _walk_members(real_type, top_die, fields)
            continue

        # Skip the 'base' field from BASE() anonymous union
        if name == "base":
            continue

        real_type = dwarf_unwrap_typedef(mtype)
        type_name = dwarf_type_name(mtype) or ""
        type_size = dwarf_byte_size(mtype)

        # Bitfield
        bit_size = child.attributes.get("DW_AT_bit_size")
        bit_off_attr = child.attributes.get("DW_AT_data_bit_offset")
        is_bf = bit_size is not None

        bf_width = bit_size.value if bit_size else 0
        bf_bit_offset = 0
        if bit_off_attr:
            bf_bit_offset = bit_off_attr.value % 8

        sf = StructField(
            name=name,
            c_type_name=type_name,
            offset=offset,
            size=type_size,
            is_bitfield=is_bf,
            bitfield_width=bf_width,
            bit_offset=bf_bit_offset,
        )

        # Array detection
        if real_type and real_type.tag == "DW_TAG_array_type":
            elem_die = dwarf_resolve_type(real_type)
            elem_name = dwarf_type_name(elem_die) or ""
            elem_size = dwarf_byte_size(elem_die) if elem_die else 0

            # Get array bound
            count = 0
            for sub in real_type.iter_children():
                if sub.tag == "DW_TAG_subrange_type":
                    ub = sub.attributes.get("DW_AT_upper_bound")
                    cnt = sub.attributes.get("DW_AT_count")
                    if ub is not None:
                        count = ub.value + 1
                    elif cnt is not None:
                        count = cnt.value
                    break

            if count == 0:
                # Flexible array member or zero-length array
                sf.is_flexible_array = True
                sf.element_type_name = elem_name
                sf.element_size = elem_size
                sf.size = 0
            elif elem_name == "char":
                sf.c_type_name = f"char[{count}]"
                sf.size = count
            else:
                sf.is_array = True
                sf.array_size = count
                sf.element_type_name = elem_name
                sf.size = type_size

        fields.append(sf)


