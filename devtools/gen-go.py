def c_to_go_name(name):
    s = name
    for prefix in ("GR_", "gr_", "CONN_S_", "DHCP_STATE_"):
        if s.startswith(prefix):
            s = s[len(prefix) :]
            break
    if s.endswith("_t"):
        s = s[:-2]
    parts = s.split("_")
    result = []
    for p in parts:
        up = p.upper()
        if up in ACRONYMS:
            result.append(up)
        else:
            result.append(p.capitalize())
    return "".join(result)


def c_struct_to_go_name(name):
    return c_to_go_name(name.lstrip("_"))


def c_enum_const_to_go(enum_name, const_name):
    return c_to_go_name(const_name)


def go_type_for_c_type(c_type, c_type_name):
    canon = c_type_name
    if canon in SPECIAL_TYPE_MAP:
        return SPECIAL_TYPE_MAP[canon][0]
    if canon in STRUCT_TYPE_MAP:
        return STRUCT_TYPE_MAP[canon]
    if canon in INT_TYPE_MAP:
        return INT_TYPE_MAP[canon]
    if canon in KNOWN_ENUMS:
        return KNOWN_ENUMS[canon]
    if canon in KNOWN_STRUCTS:
        return KNOWN_STRUCTS[canon]
    return None


